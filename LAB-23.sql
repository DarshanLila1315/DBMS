-- Part A, 1. Insert student (call twice for the two sample records)
CREATE OR ALTER PROCEDURE SP_INSERT_STUDENT
 @STDID INT,@SNAME VARCHAR(50),@CITY VARCHAR(50),@SPI DECIMAL(4,2),@BRANCH VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO STUDENT(STDID,SNAME,CITY,SPI,BRANCH) VALUES(@STDID,@SNAME,@CITY,@SPI,@BRANCH);
END;
GO
-- EXEC SP_INSERT_STUDENT 115,'PUSHTI','RAJKOT',9.48,'COMPUTER';
-- EXEC SP_INSERT_STUDENT 116,'NIKUNJ','SURAT',8.80,'CHEMICAL';

-- 2. Insert deposit
CREATE OR ALTER PROCEDURE SP_INSERT_DEPOSIT
 @ACTNO INT,@CNAME VARCHAR(50),@BNAME VARCHAR(50),@AMOUNT DECIMAL(8,2),@ADATE DATETIME
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO DEPOSIT(ACTON,CNAME,BNAME,AMOUNT,ADATE) VALUES(@ACTNO,@CNAME,@BNAME,@AMOUNT,@ADATE);
END;
GO
-- EXEC SP_INSERT_DEPOSIT 118,'HEMENT','BEDI',16000,'2025-05-05';
-- EXEC SP_INSERT_DEPOSIT 119,'RAVI','MAVDI',24000,'2024-07-09';

-- 3. Update student branch using student ID
CREATE OR ALTER PROCEDURE SP_UPDATE_STUDENT @STDID INT,@BRANCH VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 UPDATE STUDENT SET BRANCH=@BRANCH WHERE STDID=@STDID;
END;
GO
-- EXEC SP_UPDATE_STUDENT 115,'ELECTRICAL';
-- EXEC SP_UPDATE_STUDENT 116,'MECHANICAL';

-- 4. Delete students whose name is RAVI
CREATE OR ALTER PROCEDURE SP_DELETE_STUDENT
AS
BEGIN
 SET NOCOUNT ON;
 DELETE FROM STUDENT WHERE SNAME='RAVI';
END;
GO

-- 5. Select student by primary key
CREATE OR ALTER PROCEDURE SP_SELECT_STUDENT_BY_ID @STDID INT
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM STUDENT WHERE STDID=@STDID;
END;
GO

-- 6. First 5 students ordered by highest SPI
CREATE OR ALTER PROCEDURE SP_TOP5_STUDENTS
AS
BEGIN
 SET NOCOUNT ON;
 SELECT TOP (5) * FROM STUDENT ORDER BY SPI DESC;
END;
GO

-- 7. Display all employees
CREATE OR ALTER PROCEDURE SP_SELECT_ALL_EMPLOYEES
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM EMPLOYEE;
END;
GO

-- 8. Employees by department
CREATE OR ALTER PROCEDURE SP_EMPLOYEES_BY_DEPARTMENT @DepartmentName VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM EMPLOYEE WHERE DEPARTMENT=@DepartmentName;
END;
GO

-- 9. Department-wise max, min and average salary
CREATE OR ALTER PROCEDURE SP_DEPARTMENT_SALARY_STATS
AS
BEGIN
 SET NOCOUNT ON;
 SELECT DEPARTMENT,MAX(SALARY) AS MaximumSalary,MIN(SALARY) AS MinimumSalary,
        AVG(SALARY) AS AverageSalary
 FROM EMPLOYEE GROUP BY DEPARTMENT;
END;
GO

-- 10. Total salary for given department
CREATE OR ALTER PROCEDURE SP_TOTAL_SALARY_BY_DEPARTMENT @DepartmentName VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT DEPARTMENT,SUM(SALARY) AS TotalSalary
 FROM EMPLOYEE WHERE DEPARTMENT=@DepartmentName GROUP BY DEPARTMENT;
END;
GO
