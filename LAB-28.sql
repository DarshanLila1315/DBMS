CREATE OR ALTER TRIGGER trg_Insert
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    PRINT 'Employee inserted successfully';
END;
GO

CREATE OR ALTER TRIGGER trg_Update
ON EMPLOYEE AFTER UPDATE
AS
BEGIN
    PRINT 'Employee updated successfully';
END;
GO

CREATE OR ALTER TRIGGER trg_Delete
ON EMPLOYEE AFTER DELETE
AS
BEGIN
    PRINT 'Employee deleted successfully';
END;
GO

CREATE OR ALTER TRIGGER trg_Salary
ON EMPLOYEE AFTER UPDATE
AS
BEGIN
    IF UPDATE(SALARY)
       AND EXISTS (
           SELECT 1 FROM inserted i
           JOIN deleted d ON i.EID = d.EID
           WHERE i.SALARY > d.SALARY
       )
        PRINT 'Salary increased';
END;
GO

CREATE OR ALTER TRIGGER trg_CityUpper
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    UPDATE E
    SET CITY = UPPER(E.CITY)
    FROM EMPLOYEE E
    JOIN inserted I ON E.EID = I.EID
    WHERE E.CITY IS NOT NULL;
END;
GO

CREATE OR ALTER TRIGGER trg_CityChange
ON EMPLOYEE AFTER UPDATE
AS
BEGIN
    IF UPDATE(CITY)
        SELECT i.EID, d.CITY AS OldCity, i.CITY AS NewCity
        FROM inserted i
        JOIN deleted d ON i.EID = d.EID
        WHERE ISNULL(i.CITY,'') <> ISNULL(d.CITY,'');
END;
GO

CREATE OR ALTER TRIGGER trg_DefaultCity
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    UPDATE E
    SET CITY = 'RAJKOT'
    FROM EMPLOYEE E
    JOIN inserted I ON E.EID = I.EID
    WHERE E.CITY IS NULL;
END;
GO

CREATE OR ALTER TRIGGER trg_DefaultYear
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    UPDATE E
    SET JOININGYEAR = YEAR(GETDATE())
    FROM EMPLOYEE E
    JOIN inserted I ON E.EID = I.EID
    WHERE E.JOININGYEAR IS NULL;
END;
GO

CREATE OR ALTER TRIGGER trg_FullName
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    SELECT CONCAT(FIRSTNAME, ' ', LASTNAME) AS FullName
    FROM inserted;
END;
GO

CREATE OR ALTER TRIGGER trg_DefaultDept
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    UPDATE E
    SET DEPARTMENT = 'GENERAL'
    FROM EMPLOYEE E
    JOIN inserted I ON E.EID = I.EID
    WHERE E.DEPARTMENT IS NULL;
END;
GO

IF OBJECT_ID('EMPLOYEE_UPDATE_LOG', 'U') IS NULL
CREATE TABLE EMPLOYEE_UPDATE_LOG
(
    LOGID INT IDENTITY(1,1) PRIMARY KEY,
    EID INT,
    OLD_SALARY DECIMAL(10,2),
    NEW_SALARY DECIMAL(10,2),
    OLD_DEPARTMENT VARCHAR(50),
    NEW_DEPARTMENT VARCHAR(50),
    UPDATE_DATE DATETIME2
);
GO

CREATE OR ALTER TRIGGER trg_UpdateHistory
ON EMPLOYEE AFTER UPDATE
AS
BEGIN
    INSERT INTO EMPLOYEE_UPDATE_LOG
    (EID, OLD_SALARY, NEW_SALARY, OLD_DEPARTMENT,
     NEW_DEPARTMENT, UPDATE_DATE)
    SELECT i.EID, d.SALARY, i.SALARY,
           d.DEPARTMENT, i.DEPARTMENT, GETDATE()
    FROM inserted i
    JOIN deleted d ON i.EID = d.EID;
END;
GO

IF OBJECT_ID('EMPLOYEE_INSERT_LOG', 'U') IS NULL
CREATE TABLE EMPLOYEE_INSERT_LOG
(
    LOGID INT IDENTITY(1,1) PRIMARY KEY,
    EID INT,
    FULLNAME VARCHAR(120),
    INSERT_DATE DATETIME2
);
GO

CREATE OR ALTER TRIGGER trg_InsertHistory
ON EMPLOYEE AFTER INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE_INSERT_LOG
    (EID, FULLNAME, INSERT_DATE)
    SELECT EID, CONCAT(FIRSTNAME, ' ', LASTNAME), GETDATE()
    FROM inserted;
END;
GO

