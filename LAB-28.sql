-- 15. INSTEAD OF INSERT: trim extra spaces from first and last name
-- This trigger explicitly inserts valid rows into EMPLOYEE.
CREATE OR ALTER TRIGGER dbo.trg_Employee_TrimNames_Insert
ON dbo.EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.EMPLOYEE(EID,FIRSTNAME,LASTNAME,DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR)
 SELECT EID,LTRIM(RTRIM(FIRSTNAME)),LTRIM(RTRIM(LASTNAME)),DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR
 FROM inserted;
END;
GO
