-- 4. Message after salary increment (salary increases on update)
CREATE OR ALTER TRIGGER dbo.trg_Employee_SalaryIncrement_Message
ON dbo.EMPLOYEE AFTER UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(SALARY) AND EXISTS
 (SELECT 1 FROM inserted i JOIN deleted d ON i.EID=d.EID WHERE i.SALARY>d.SALARY)
 PRINT 'Employee salary incremented.';
END;
GO

-- 5. Uppercase city on insert (AFTER trigger normalizes inserted rows)
CREATE OR ALTER TRIGGER dbo.trg_Employee_CityUppercase
ON dbo.EMPLOYEE AFTER INSERT
AS
BEGIN
 SET NOCOUNT ON;
 UPDATE E SET CITY=UPPER(E.CITY)
 FROM dbo.EMPLOYEE E JOIN inserted I ON E.EID=I.EID
 WHERE E.CITY IS NOT NULL AND E.CITY<>UPPER(E.CITY);
END;
GO

-- 6. Print old and new city after city update
CREATE OR ALTER TRIGGER dbo.trg_Employee_CityChange_Message
ON dbo.EMPLOYEE AFTER UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(CITY)
 SELECT CONCAT('EID ',i.EID,': old city=',COALESCE(d.CITY,'NULL'),
               ', new city=',COALESCE(i.CITY,'NULL')) AS CityChange
 FROM inserted i JOIN deleted d ON i.EID=d.EID
 WHERE ISNULL(i.CITY,'')<>ISNULL(d.CITY,'');
END;
GO

-- 7. Set city to RAJKOT when omitted or NULL on insert
-- AFTER trigger can normalize NULL values; omitted values must allow NULL/default.
CREATE OR ALTER TRIGGER dbo.trg_Employee_DefaultCity
ON dbo.EMPLOYEE AFTER INSERT
AS
BEGIN
 SET NOCOUNT ON;
 UPDATE E SET CITY='RAJKOT'
 FROM dbo.EMPLOYEE E JOIN inserted I ON E.EID=I.EID
 WHERE E.CITY IS NULL;
