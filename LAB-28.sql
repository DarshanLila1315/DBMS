CREATE OR ALTER TRIGGER trg_TrimNames
ON EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
    INSERT INTO EMPLOYEE
    (EID, FIRSTNAME, LASTNAME, DEPARTMENT,
     SALARY, CITY, GENDER, JOININGYEAR)
    SELECT EID, LTRIM(RTRIM(FIRSTNAME)),
           LTRIM(RTRIM(LASTNAME)), DEPARTMENT,
           SALARY, CITY, GENDER, JOININGYEAR
    FROM inserted;
END;
GO
