-- 11. Create log table for salary/department updates, if it doesn't exist
IF OBJECT_ID('dbo.EMPLOYEE_UPDATE_LOG','U') IS NULL
CREATE TABLE dbo.EMPLOYEE_UPDATE_LOG
(
 LOGID INT IDENTITY(1,1) PRIMARY KEY,
 EID INT, OLD_SALARY DECIMAL(10,2), NEW_SALARY DECIMAL(10,2),
 OLD_DEPARTMENT VARCHAR(50), NEW_DEPARTMENT VARCHAR(50), UPDATE_DATE DATETIME2
);
GO
CREATE OR ALTER TRIGGER dbo.trg_Employee_UpdateHistory
ON dbo.EMPLOYEE AFTER UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.EMPLOYEE_UPDATE_LOG(EID,OLD_SALARY,NEW_SALARY,OLD_DEPARTMENT,NEW_DEPARTMENT,UPDATE_DATE)
 SELECT i.EID,d.SALARY,i.SALARY,d.DEPARTMENT,i.DEPARTMENT,SYSDATETIME()
 FROM inserted i JOIN deleted d ON i.EID=d.EID
 WHERE ISNULL(i.SALARY,-1)<>ISNULL(d.SALARY,-1)
    OR ISNULL(i.DEPARTMENT,'')<>ISNULL(d.DEPARTMENT,'');
END;
GO

-- 12. Insert log table and trigger
IF OBJECT_ID('dbo.EMPLOYEE_INSERT_LOG','U') IS NULL
CREATE TABLE dbo.EMPLOYEE_INSERT_LOG
(
 LOGID INT IDENTITY(1,1) PRIMARY KEY,EID INT,FULLNAME VARCHAR(120),INSERT_DATE DATETIME2
);
GO
CREATE OR ALTER TRIGGER dbo.trg_Employee_InsertHistory
ON dbo.EMPLOYEE AFTER INSERT
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.EMPLOYEE_INSERT_LOG(EID,FULLNAME,INSERT_DATE)
 SELECT EID,CONCAT(FIRSTNAME,' ',LASTNAME),SYSDATETIME() FROM inserted;
END;
GO

