-- 1. Message after employee insert
CREATE OR ALTER TRIGGER dbo.trg_Employee_AfterInsert_Message
ON dbo.EMPLOYEE AFTER INSERT
AS
BEGIN
 SET NOCOUNT ON;
 PRINT 'Employee record inserted successfully.';
END;
GO

