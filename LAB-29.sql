
CREATE TABLE dbo.EMPLOYEE_LOG
(
    LOGID INT IDENTITY(1,1) PRIMARY KEY,
    EID INT,
    OLDVALUE VARCHAR(4000),
    NEWVALUE VARCHAR(4000),
    FIELDNAME VARCHAR(100),
    OPERATIONTYPE VARCHAR(20),
    LOGDATE DATETIME2
);
GO

CREATE OR ALTER TRIGGER trg_PreventDelete
ON EMPLOYEE INSTEAD OF DELETE
AS
BEGIN
    PRINT 'Employee deletion is not allowed.';
END;
GO

CREATE OR ALTER TRIGGER trg_PreventDeleteLog
ON EMPLOYEE INSTEAD OF DELETE
AS
BEGIN
    INSERT INTO EMPLOYEE_LOG
    (EID, OLDVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
    SELECT EID, CONCAT(FIRSTNAME, ' ', LASTNAME),
           'EMPLOYEE', 'DELETE_BLOCKED', GETDATE()
    FROM deleted;
END;
GO

CREATE OR ALTER TRIGGER trg_LogAll
ON EMPLOYEE INSTEAD OF INSERT, UPDATE, DELETE
AS
BEGIN
    IF EXISTS(SELECT 1 FROM inserted)
       AND EXISTS(SELECT 1 FROM deleted)
    BEGIN
        INSERT INTO EMPLOYEE_LOG
        (EID, OLDVALUE, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
        SELECT i.EID, d.FIRSTNAME, i.FIRSTNAME,
               'EMPLOYEE', 'UPDATE', GETDATE()
        FROM inserted i JOIN deleted d ON i.EID = d.EID;

        UPDATE E
        SET FIRSTNAME = i.FIRSTNAME,
            LASTNAME = i.LASTNAME,
            DEPARTMENT = i.DEPARTMENT,
            SALARY = i.SALARY,
            CITY = i.CITY,
            GENDER = i.GENDER,
            JOININGYEAR = i.JOININGYEAR
        FROM EMPLOYEE E JOIN inserted i ON E.EID = i.EID;
    END
    ELSE IF EXISTS(SELECT 1 FROM inserted)
    BEGIN
        INSERT INTO EMPLOYEE_LOG
        (EID, NEWVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
        SELECT EID, FIRSTNAME, 'EMPLOYEE', 'INSERT', GETDATE()
        FROM inserted;

        INSERT INTO EMPLOYEE
        (EID, FIRSTNAME, LASTNAME, DEPARTMENT,
         SALARY, CITY, GENDER, JOININGYEAR)
        SELECT EID, FIRSTNAME, LASTNAME, DEPARTMENT,
               SALARY, CITY, GENDER, JOININGYEAR
        FROM inserted;
    END
    ELSE
    BEGIN
        INSERT INTO EMPLOYEE_LOG
        (EID, OLDVALUE, FIELDNAME, OPERATIONTYPE, LOGDATE)
        SELECT EID, FIRSTNAME, 'EMPLOYEE', 'DELETE', GETDATE()
        FROM deleted;

        DELETE E
        FROM EMPLOYEE E JOIN deleted d ON E.EID = d.EID;
    END
END;
GO

