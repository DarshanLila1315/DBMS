       '; BRANCH=',COALESCE(BRANCH,'NULL')),NULL,'STUDENT','DELETE',SYSDATETIME()
 FROM deleted;
 PRINT 'Student deletion intercepted and logged; base records were retained.';
END;
GO

-- 14. Prevent updating student SPI
CREATE OR ALTER TRIGGER dbo.trg_Student_PreventSPIUpdate
ON dbo.STUDENT INSTEAD OF UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(SPI) AND EXISTS
 (SELECT 1 FROM inserted i JOIN deleted d ON i.STDID=d.STDID WHERE ISNULL(i.SPI,-1)<>ISNULL(d.SPI,-1))
 BEGIN PRINT 'Student SPI cannot be updated.'; RETURN; END;
 UPDATE S SET SNAME=i.SNAME,CITY=i.CITY,BRANCH=i.BRANCH
 FROM dbo.STUDENT S JOIN inserted i ON S.STDID=i.STDID;
END;
GO

-- 15. Log branch transfer history and perform branch update
CREATE OR ALTER TRIGGER dbo.trg_Student_BranchTransferHistory
ON dbo.STUDENT AFTER UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(BRANCH)
 INSERT INTO dbo.STUDENT_LOG(STDID,SNAME,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
 SELECT i.STDID,i.SNAME,d.BRANCH,i.BRANCH,'BRANCH','UPDATE',SYSDATETIME()
 FROM inserted i JOIN deleted d ON i.STDID=d.STDID
 WHERE ISNULL(i.BRANCH,'')<>ISNULL(d.BRANCH,'');
END;
GO
