CREATE TABLE dbo.STUDENT_LOG
(
    LOGID INT IDENTITY(1,1) PRIMARY KEY,
    STDID INT,
    SNAME VARCHAR(50),
    OLDVALUE VARCHAR(4000),
    NEWVALUE VARCHAR(4000),
    FIELDNAME VARCHAR(100),
    OPERATIONTYPE VARCHAR(20),
    LOGDATE DATETIME2
);
GO

CREATE OR ALTER TRIGGER trg_ValidateSPI
ON STUDENT INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM inserted
        WHERE SPI < 0 OR SPI > 10 OR SPI IS NULL
    )
    BEGIN
        PRINT 'SPI must be between 0 and 10.';
        RETURN;
    END;

    INSERT INTO STUDENT(STDID, SNAME, CITY, SPI, BRANCH)
    SELECT STDID, SNAME, CITY, SPI, BRANCH FROM inserted;
END;
GO

