-- Create common employee log table required by Lab 29
IF OBJECT_ID('dbo.EMPLOYEE_LOG','U') IS NULL
CREATE TABLE dbo.EMPLOYEE_LOG
(
 LOGID INT IDENTITY(1,1) PRIMARY KEY,
 EID INT NULL, OLDVALUE VARCHAR(4000) NULL, NEWVALUE VARCHAR(4000) NULL,
 FIELDNAME VARCHAR(100) NULL, OPERATIONTYPE VARCHAR(20) NULL, LOGDATE DATETIME2
);
GO

-- 1. Prevent employee deletion (instead of delete)
CREATE OR ALTER TRIGGER dbo.trg_Employee_PreventDelete
ON dbo.EMPLOYEE INSTEAD OF DELETE
AS
BEGIN
 SET NOCOUNT ON;
 PRINT 'Employee deletion is not allowed.';
END;
GO

-- 2. Prevent deletion and log deleted employee details
CREATE OR ALTER TRIGGER dbo.trg_Employee_PreventDeleteAndLog
ON dbo.EMPLOYEE INSTEAD OF DELETE
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
 SELECT EID,CONCAT(FIRSTNAME,' ',LASTNAME,'; Department=',COALESCE(DEPARTMENT,'NULL'),
       '; Salary=',SALARY),NULL,'EMPLOYEE','DELETE_BLOCKED',SYSDATETIME()
 FROM deleted;
 PRINT 'Employee deletion blocked; deleted details logged.';
END;
GO

-- 3. Log INSERT/UPDATE/DELETE using INSTEAD OF trigger
-- This example logs and then performs the requested operation.
-- Create this trigger instead of other INSTEAD OF triggers on EMPLOYEE.
CREATE OR ALTER TRIGGER dbo.trg_Employee_LogAllOperations
ON dbo.EMPLOYEE INSTEAD OF INSERT,UPDATE,DELETE
AS
BEGIN
 SET NOCOUNT ON;

 IF EXISTS(SELECT 1 FROM inserted) AND EXISTS(SELECT 1 FROM deleted)
 BEGIN
   INSERT INTO dbo.EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
   SELECT i.EID,CONCAT(d.FIRSTNAME,' ',d.LASTNAME,' Salary=',d.SALARY),
          CONCAT(i.FIRSTNAME,' ',i.LASTNAME,' Salary=',i.SALARY),
          'EMPLOYEE','UPDATE',SYSDATETIME()
   FROM inserted i JOIN deleted d ON i.EID=d.EID;

   UPDATE E SET FIRSTNAME=i.FIRSTNAME,LASTNAME=i.LASTNAME,DEPARTMENT=i.DEPARTMENT,
      SALARY=i.SALARY,CITY=i.CITY,GENDER=i.GENDER,JOININGYEAR=i.JOININGYEAR
   FROM dbo.EMPLOYEE E JOIN inserted i ON E.EID=i.EID;
 END
 ELSE IF EXISTS(SELECT 1 FROM inserted)
 BEGIN
   INSERT INTO dbo.EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
   SELECT EID,NULL,CONCAT(FIRSTNAME,' ',LASTNAME),'EMPLOYEE','INSERT',SYSDATETIME() FROM inserted;

   INSERT INTO dbo.EMPLOYEE(EID,FIRSTNAME,LASTNAME,DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR)
   SELECT i.EID,i.FIRSTNAME,i.LASTNAME,i.DEPARTMENT,i.SALARY,i.CITY,i.GENDER,i.JOININGYEAR
   FROM inserted i
   WHERE NOT EXISTS(SELECT 1 FROM dbo.EMPLOYEE e WHERE e.EID=i.EID);
 END
 ELSE
 BEGIN
   INSERT INTO dbo.EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
   SELECT EID,CONCAT(FIRSTNAME,' ',LASTNAME),NULL,'EMPLOYEE','DELETE',SYSDATETIME() FROM deleted;
   DELETE E FROM dbo.EMPLOYEE E JOIN deleted d ON E.EID=d.EID;
 END
END;
GO

-- 4. Block updates to JOININGYEAR
CREATE OR ALTER TRIGGER dbo.trg_Employee_BlockJoiningYearUpdate
ON dbo.EMPLOYEE INSTEAD OF UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(JOININGYEAR)
 BEGIN
   PRINT 'Employees are not allowed to update their joining year';
   RETURN;
 END;
 UPDATE E SET FIRSTNAME=i.FIRSTNAME,LASTNAME=i.LASTNAME,DEPARTMENT=i.DEPARTMENT,
   SALARY=i.SALARY,CITY=i.CITY,GENDER=i.GENDER
 FROM dbo.EMPLOYEE E JOIN inserted i ON E.EID=i.EID;
END;
GO

-- 5. Prevent duplicate FIRSTNAME + LASTNAME + CITY
CREATE OR ALTER TRIGGER dbo.trg_Employee_PreventDuplicatePerson
ON dbo.EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS
 (
  SELECT 1 FROM inserted i JOIN dbo.EMPLOYEE e
    ON e.FIRSTNAME=i.FIRSTNAME AND e.LASTNAME=i.LASTNAME AND ISNULL(e.CITY,'')=ISNULL(i.CITY,'')
 )
 BEGIN PRINT 'Duplicate employee (first name, last name, city) is not allowed.'; RETURN; END;
 INSERT INTO dbo.EMPLOYEE(EID,FIRSTNAME,LASTNAME,DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR)
 SELECT i.EID,i.FIRSTNAME,i.LASTNAME,i.DEPARTMENT,i.SALARY,i.CITY,i.GENDER,i.JOININGYEAR
 FROM inserted i;
END;
GO

-- 6. Prevent duplicate EID on insert
CREATE OR ALTER TRIGGER dbo.trg_Employee_PreventDuplicateEID
ON dbo.EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS(SELECT 1 FROM inserted i JOIN dbo.EMPLOYEE e ON e.EID=i.EID)
 BEGIN PRINT 'Duplicate EID is not allowed.'; RETURN; END;
 INSERT INTO dbo.EMPLOYEE(EID,FIRSTNAME,LASTNAME,DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR)
 SELECT EID,FIRSTNAME,LASTNAME,DEPARTMENT,SALARY,CITY,GENDER,JOININGYEAR FROM inserted;
END;
GO

-- 7. INSTEAD OF UPDATE: log complete update history and perform update
CREATE OR ALTER TRIGGER dbo.trg_Employee_UpdateLogInsteadOf
ON dbo.EMPLOYEE INSTEAD OF UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.EMPLOYEE_LOG(EID,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
 SELECT i.EID,
        CONCAT('Name=',d.FIRSTNAME,' ',d.LASTNAME,'; Dept=',COALESCE(d.DEPARTMENT,'NULL'),
               '; Salary=',d.SALARY,'; City=',COALESCE(d.CITY,'NULL')),
        CONCAT('Name=',i.FIRSTNAME,' ',i.LASTNAME,'; Dept=',COALESCE(i.DEPARTMENT,'NULL'),
               '; Salary=',i.SALARY,'; City=',COALESCE(i.CITY,'NULL')),
        'ALL COLUMNS','UPDATE',SYSDATETIME()
 FROM inserted i JOIN deleted d ON i.EID=d.EID;
 UPDATE E SET FIRSTNAME=i.FIRSTNAME,LASTNAME=i.LASTNAME,DEPARTMENT=i.DEPARTMENT,
   SALARY=i.SALARY,CITY=i.CITY,GENDER=i.GENDER,JOININGYEAR=i.JOININGYEAR
 FROM dbo.EMPLOYEE E JOIN inserted i ON E.EID=i.EID;
END;
GO

-- 8. Prevent changing EID
CREATE OR ALTER TRIGGER dbo.trg_Employee_PreventEIDUpdate
ON dbo.EMPLOYEE INSTEAD OF UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(EID) AND EXISTS(SELECT 1 FROM inserted i JOIN deleted d ON i.EID<>d.EID)
 BEGIN PRINT 'Employee EID cannot be changed.'; RETURN; END;
 UPDATE E SET FIRSTNAME=i.FIRSTNAME,LASTNAME=i.LASTNAME,DEPARTMENT=i.DEPARTMENT,
   SALARY=i.SALARY,CITY=i.CITY,GENDER=i.GENDER,JOININGYEAR=i.JOININGYEAR
 FROM dbo.EMPLOYEE E JOIN inserted i ON E.EID=i.EID;
END;
GO

-- 9. Block insert when department is NULL
CREATE OR ALTER TRIGGER dbo.trg_Employee_BlockNullDepartment
ON dbo.EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
