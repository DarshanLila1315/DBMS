CREATE OR ALTER TRIGGER trg_BranchHistory
ON STUDENT AFTER UPDATE
AS
BEGIN
    IF UPDATE(BRANCH)
    INSERT INTO STUDENT_LOG
    (STDID, SNAME, OLDVALUE, NEWVALUE,
     FIELDNAME, OPERATIONTYPE, LOGDATE)
    SELECT i.STDID, i.SNAME, d.BRANCH, i.BRANCH,
           'BRANCH', 'UPDATE', GETDATE()
    FROM inserted i JOIN deleted d ON i.STDID = d.STDID
    WHERE ISNULL(i.BRANCH, '') <> ISNULL(d.BRANCH, '');
END;
GO
