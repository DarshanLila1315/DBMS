GO

CREATE OR ALTER TRIGGER trg_PreventDuplicatePerson
ON EMPLOYEE INSTEAD OF INSERT
AS
BEGIN
    IF EXISTS
    (
        SELECT 1 FROM inserted i
        JOIN EMPLOYEE e
        ON e.FIRSTNAME = i.FIRSTNAME
        AND e.LASTNAME = i.LASTNAME
        AND ISNULL(e.CITY, '') = ISNULL(i.CITY, '')
    )
    BEGIN
        PRINT 'Duplicate employee is not allowed.';
        RETURN;
    END;

    INSERT INTO EMPLOYEE
    (EID, FIRSTNAME, LASTNAME, DEPARTMENT,
     SALARY, CITY, GENDER, JOININGYEAR)
    SELECT EID, FIRSTNAME, LASTNAME, DEPARTMENT,
           SALARY, CITY, GENDER, JOININGYEAR
    FROM inserted;
END;
GO

