-- 11. Block student insert if SPI outside 0..10
CREATE OR ALTER TRIGGER dbo.trg_Student_ValidateSPI
ON dbo.STUDENT INSTEAD OF INSERT
AS
BEGIN
 SET NOCOUNT ON;
 IF EXISTS(SELECT 1 FROM inserted WHERE SPI<0 OR SPI>10 OR SPI IS NULL)
 BEGIN PRINT 'SPI must be between 0 and 10.'; RETURN; END;
 INSERT INTO dbo.STUDENT(STDID,SNAME,CITY,SPI,BRANCH)
 SELECT STDID,SNAME,CITY,SPI,BRANCH FROM inserted;
END;
GO

-- 12. Block changing student BRANCH after admission
CREATE OR ALTER TRIGGER dbo.trg_Student_PreventBranchUpdate
ON dbo.STUDENT INSTEAD OF UPDATE
AS
BEGIN
 SET NOCOUNT ON;
 IF UPDATE(BRANCH) AND EXISTS
 (SELECT 1 FROM inserted i JOIN deleted d ON i.STDID=d.STDID WHERE ISNULL(i.BRANCH,'')<>ISNULL(d.BRANCH,''))
 BEGIN PRINT 'Student branch cannot be changed after admission.'; RETURN; END;
 UPDATE S SET SNAME=i.SNAME,CITY=i.CITY,SPI=i.SPI
 FROM dbo.STUDENT S JOIN inserted i ON S.STDID=i.STDID;
END;
GO

-- 13. Log deleted students instead of permanently deleting
CREATE OR ALTER TRIGGER dbo.trg_Student_LogDelete
ON dbo.STUDENT INSTEAD OF DELETE
AS
BEGIN
 SET NOCOUNT ON;
 INSERT INTO dbo.STUDENT_LOG(STDID,SNAME,OLDVALUE,NEWVALUE,FIELDNAME,OPERATIONTYPE,LOGDATE)
