-- Part A, 1. Department salary statistics
CREATE OR ALTER PROCEDURE SP_DEPARTMENT_STATS @DepartmentName VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT DEPARTMENT,SUM(SALARY) AS TotalSalary,AVG(SALARY) AS AverageSalary,
        MIN(SALARY) AS MinimumSalary,MAX(SALARY) AS MaximumSalary
 FROM EMPLOYEE WHERE DEPARTMENT=@DepartmentName GROUP BY DEPARTMENT;
END;
GO

-- 2. Employees who joined a given year
CREATE OR ALTER PROCEDURE SP_EMPLOYEES_BY_JOINING_YEAR @Year INT
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM EMPLOYEE WHERE JOININGYEAR=@Year;
END;
GO

-- 3. Dynamic search by partial city name
CREATE OR ALTER PROCEDURE SP_SEARCH_EMPLOYEE_BY_CITY @CityPart VARCHAR(100)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM EMPLOYEE WHERE CITY LIKE '%' + @CityPart + '%';
END;
GO

-- 4. Employees earning more than supplied salary
CREATE OR ALTER PROCEDURE SP_EMPLOYEES_ABOVE_SALARY @Salary DECIMAL(10,2)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM EMPLOYEE WHERE SALARY>@Salary ORDER BY SALARY DESC;
END;
GO

-- 5. Top N highest paid employees from each department
CREATE OR ALTER PROCEDURE SP_TOP_N_BY_DEPARTMENT @N INT
AS
BEGIN
 SET NOCOUNT ON;
 IF @N<1 THROW 50001,'N must be greater than zero.',1;
 WITH E AS
 (SELECT *,ROW_NUMBER() OVER(PARTITION BY DEPARTMENT ORDER BY SALARY DESC,EID) AS rn FROM EMPLOYEE)
 SELECT * FROM E WHERE rn<=@N ORDER BY DEPARTMENT,SALARY DESC;
END;
GO

-- 6. Increase salary in a department by percentage
CREATE OR ALTER PROCEDURE SP_INCREMENT_DEPARTMENT_SALARY
 @DepartmentName VARCHAR(50),@Percent DECIMAL(6,2)
AS
BEGIN
 SET NOCOUNT ON;
 IF @Percent<0 THROW 50002,'Percentage cannot be negative.',1;
 UPDATE EMPLOYEE SET SALARY=SALARY*(1+@Percent/100.0) WHERE DEPARTMENT=@DepartmentName;
 SELECT @@ROWCOUNT AS UpdatedEmployees;
END;
GO

-- 7. Employees with experience >= entered years
CREATE OR ALTER PROCEDURE SP_EMPLOYEES_BY_EXPERIENCE @Years INT
AS
BEGIN
 SET NOCOUNT ON;
 SELECT *,YEAR(GETDATE())-JOININGYEAR AS ExperienceYears
 FROM EMPLOYEE WHERE YEAR(GETDATE())-JOININGYEAR>=@Years;
END;
GO

-- 8. Last N employees who joined (most recent joining year first)
CREATE OR ALTER PROCEDURE SP_LAST_N_EMPLOYEES @N INT
AS
BEGIN
 SET NOCOUNT ON;
 IF @N<1 THROW 50003,'N must be greater than zero.',1;
 SELECT TOP (@N) * FROM EMPLOYEE ORDER BY JOININGYEAR DESC,EID DESC;
END;
GO

-- Part B, 9. Books by author name
CREATE OR ALTER PROCEDURE SP_BOOKS_BY_AUTHOR @AuthorName VARCHAR(100)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT B.*,A.AUTHORNAME FROM BOOK B
 JOIN AUTHOR A ON A.AUTHORID=B.AUTHORID
 WHERE A.AUTHORNAME=@AuthorName;
END;
GO

-- 10. Books published after a given year
CREATE OR ALTER PROCEDURE SP_BOOKS_AFTER_YEAR @Year INT
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM BOOK WHERE PUBLICATIONYEAR>@Year ORDER BY PUBLICATIONYEAR;
END;
GO

-- 11. Authors from country with their books
CREATE OR ALTER PROCEDURE SP_AUTHORS_BOOKS_BY_COUNTRY @Country VARCHAR(50)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT A.AUTHORID,A.AUTHORNAME,A.COUNTRY,B.BOOKID,B.TITLE,B.PRICE,B.PUBLICATIONYEAR
 FROM AUTHOR A LEFT JOIN BOOK B ON B.AUTHORID=A.AUTHORID
 WHERE A.COUNTRY=@Country;
END;
GO

-- 12. Top N most expensive books with author and publisher
CREATE OR ALTER PROCEDURE SP_TOP_N_EXPENSIVE_BOOKS @N INT
AS
BEGIN
 SET NOCOUNT ON;
 IF @N<1 THROW 50004,'N must be greater than zero.',1;
 SELECT TOP (@N) B.BOOKID,B.TITLE,B.PRICE,B.PUBLICATIONYEAR,
        A.AUTHORNAME,P.PUBLISHERNAME
 FROM BOOK B JOIN AUTHOR A ON A.AUTHORID=B.AUTHORID
 JOIN PUBLISHER P ON P.PUBLISHERID=B.PUBLISHERID
 ORDER BY B.PRICE DESC,B.BOOKID;
END;
GO

-- Part C, 13. Total books by publisher
CREATE OR ALTER PROCEDURE SP_BOOK_COUNT_BY_PUBLISHER @PublisherName VARCHAR(100)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT P.PUBLISHERNAME,COUNT(B.BOOKID) AS TotalBooks
 FROM PUBLISHER P LEFT JOIN BOOK B ON B.PUBLISHERID=P.PUBLISHERID
 WHERE P.PUBLISHERNAME=@PublisherName GROUP BY P.PUBLISHERNAME;
END;
GO

-- 14. Books within price range
CREATE OR ALTER PROCEDURE SP_BOOKS_BY_PRICE_RANGE @MinPrice DECIMAL(8,2),@MaxPrice DECIMAL(8,2)
AS
BEGIN
 SET NOCOUNT ON;
 SELECT * FROM BOOK WHERE PRICE BETWEEN @MinPrice AND @MaxPrice ORDER BY PRICE;
END;
GO

-- 15. Delete books by author ID
CREATE OR ALTER PROCEDURE SP_DELETE_BOOKS_BY_AUTHOR @AuthorID INT
AS
BEGIN
 SET NOCOUNT ON;
 DELETE FROM BOOK WHERE AUTHORID=@AuthorID;
 SELECT @@ROWCOUNT AS DeletedBooks;
END;
GO
