-- 1. Top 3 highest amount orders

WITH C AS (SELECT *, ROW_NUMBER() OVER(ORDER BY AMOUNT DESC) AS rn FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,PRODUCT,CATEGORY,AMOUNT,ORDERYEAR,CITY FROM C WHERE rn<=3;

-- 2. Second-highest distinct order amount

WITH A AS (SELECT DISTINCT AMOUNT FROM CUSTOMER_ALL),
R AS (SELECT AMOUNT,DENSE_RANK() OVER(ORDER BY AMOUNT DESC) AS rnk FROM A)
SELECT AMOUNT FROM R WHERE rnk=2;

-- 3. Orders greater than their category average

WITH C AS (SELECT *,AVG(AMOUNT*1.0) OVER(PARTITION BY CATEGORY) AS CatAvg FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,PRODUCT,CATEGORY,AMOUNT,CITY FROM C WHERE AMOUNT>CatAvg;

-- 4. Categories with average amount > 30000

WITH C AS (SELECT CATEGORY,AVG(AMOUNT*1.0) AS AvgAmount FROM CUSTOMER_ALL GROUP BY CATEGORY)
SELECT CATEGORY,AvgAmount FROM C WHERE AvgAmount>30000;

-- 5. Highest amount order from each category (includes ties)
WITH C AS (SELECT *,RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC) AS rnk FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,PRODUCT,CATEGORY,AMOUNT FROM C WHERE rnk=1;

-- 6. Lowest amount order from each category (includes ties)
WITH C AS (SELECT *,RANK() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT ASC) AS rnk FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,PRODUCT,CATEGORY,AMOUNT FROM C WHERE rnk=1;

-- 7. Categories having more than 3 orders
WITH C AS (SELECT CATEGORY,COUNT(*) AS OrderCount FROM CUSTOMER_ALL GROUP BY CATEGORY)
SELECT CATEGORY,OrderCount FROM C WHERE OrderCount>3;

-- 8. City-wise total order amount
WITH C AS (SELECT CITY,SUM(AMOUNT) AS TotalAmount FROM CUSTOMER_ALL GROUP BY CITY)
SELECT CITY,TotalAmount FROM C ORDER BY CITY;

-- 9. Category having highest average order amount
WITH C AS (SELECT CATEGORY,AVG(AMOUNT*1.0) AS AvgAmount FROM CUSTOMER_ALL GROUP BY CATEGORY),
R AS (SELECT *,DENSE_RANK() OVER(ORDER BY AvgAmount DESC) AS rnk FROM C)
SELECT CATEGORY,AvgAmount FROM R WHERE rnk=1;

-- 10. Cumulative order amount in ascending amount order
WITH C AS (SELECT *,SUM(AMOUNT) OVER(ORDER BY AMOUNT,ORDERID ROWS UNBOUNDED PRECEDING) AS RunningTotal FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,AMOUNT,RunningTotal FROM C ORDER BY AMOUNT,ORDERID;

-- 11. Category-wise top 2 highest amount orders
WITH C AS (SELECT *,ROW_NUMBER() OVER(PARTITION BY CATEGORY ORDER BY AMOUNT DESC,ORDERID) AS rn FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,CATEGORY,AMOUNT FROM C WHERE rn<=2;

-- 12. Customers whose amount is closest to category average (ties included)
WITH C AS (SELECT *,AVG(AMOUNT*1.0) OVER(PARTITION BY CATEGORY) AS CatAvg FROM CUSTOMER_ALL),
D AS (SELECT *,ABS(AMOUNT-CatAvg) AS Diff FROM C),
R AS (SELECT *,MIN(Diff) OVER(PARTITION BY CATEGORY) AS MinDiff FROM D)
SELECT ORDERID,CNAME,CATEGORY,AMOUNT,CatAvg FROM R WHERE Diff=MinDiff;

-- 13. Previous, current and next order amount by order ID
WITH C AS (SELECT ORDERID,CNAME,AMOUNT,
 LAG(AMOUNT) OVER(ORDER BY ORDERID) AS PreviousAmount,
 LEAD(AMOUNT) OVER(ORDER BY ORDERID) AS NextAmount FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,PreviousAmount,AMOUNT AS CurrentAmount,NextAmount FROM C;

-- 14. Customers whose amount is greater than previous customer's amount
WITH C AS (SELECT ORDERID,CNAME,AMOUNT,LAG(AMOUNT) OVER(ORDER BY ORDERID) AS PreviousAmount FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,AMOUNT,PreviousAmount FROM C WHERE AMOUNT>PreviousAmount;

-- 15. Customers whose rank and dense rank are different
WITH C AS (SELECT *,RANK() OVER(ORDER BY AMOUNT DESC) AS AmountRank,
 DENSE_RANK() OVER(ORDER BY AMOUNT DESC) AS AmountDenseRank FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,AMOUNT,AmountRank,AmountDenseRank FROM C WHERE AmountRank<>AmountDenseRank;

-- 16. Orders neither highest nor lowest in their category
WITH C AS (SELECT *,MIN(AMOUNT) OVER(PARTITION BY CATEGORY) AS MinAmount,
 MAX(AMOUNT) OVER(PARTITION BY CATEGORY) AS MaxAmount FROM CUSTOMER_ALL)
SELECT ORDERID,CNAME,CATEGORY,AMOUNT FROM C WHERE AMOUNT<>MinAmount AND AMOUNT<>MaxAmount;

-- 17. Category-wise difference between highest and lowest amount
WITH C AS (SELECT CATEGORY,MAX(AMOUNT) AS MaxAmount,MIN(AMOUNT) AS MinAmount FROM CUSTOMER_ALL GROUP BY CATEGORY)
SELECT CATEGORY,MaxAmount,MinAmount,MaxAmount-MinAmount AS Difference FROM C;

-- 18. Customers whose amount is greater than all FURNITURE orders
WITH F AS (SELECT MAX(AMOUNT) AS MaxFurniture FROM CUSTOMER_ALL WHERE CATEGORY='FURNITURE')
SELECT ORDERID,CNAME,CATEGORY,AMOUNT FROM CUSTOMER_ALL WHERE AMOUNT>(SELECT MaxFurniture FROM F);

-- 19. Categories where all orders are above 10000
WITH C AS (SELECT CATEGORY,MIN(AMOUNT) AS MinAmount FROM CUSTOMER_ALL GROUP BY CATEGORY)
SELECT CATEGORY FROM C WHERE MinAmount>10000;

-- 20. Customers whose amount difference from category topper is minimum
WITH C AS (SELECT *,MAX(AMOUNT) OVER(PARTITION BY CATEGORY) AS TopAmount FROM CUSTOMER_ALL),
D AS (SELECT *,ABS(TopAmount-AMOUNT) AS Diff FROM C),
R AS (SELECT *,MIN(Diff) OVER(PARTITION BY CATEGORY) AS MinDiff FROM D)
SELECT ORDERID,CNAME,CATEGORY,AMOUNT,TopAmount FROM R WHERE Diff=MinDiff;