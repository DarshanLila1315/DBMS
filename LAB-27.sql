
-- 1. Display all employees
DECLARE @ID INT, @Name VARCHAR(50);
DECLARE C1 CURSOR FOR
SELECT EID, FIRSTNAME FROM EMPLOYEE;
OPEN C1;
FETCH NEXT FROM C1 INTO @ID, @Name;
WHILE @@FETCH_STATUS = 0
BEGIN
    PRINT CONCAT(@ID, ' ', @Name);
    FETCH NEXT FROM C1 INTO @ID, @Name;
END;
CLOSE C1;
DEALLOCATE C1;
GO

