-- 19. Employees earning above department average
DECLARE @Name VARCHAR(50), @Sal DECIMAL(10,2);
DECLARE C1 CURSOR FOR
SELECT FIRSTNAME, SALARY
FROM EMPLOYEE E
WHERE SALARY >
(
    SELECT AVG(SALARY)
    FROM EMPLOYEE
    WHERE DEPARTMENT = E.DEPARTMENT
);
OPEN C1;
FETCH NEXT FROM C1 INTO @Name, @Sal;
WHILE @@FETCH_STATUS = 0
BEGIN
    PRINT CONCAT(@Name, ' ', @Sal);
    FETCH NEXT FROM C1 INTO @Name, @Sal;
END;
CLOSE C1;
DEALLOCATE C1;
GO

